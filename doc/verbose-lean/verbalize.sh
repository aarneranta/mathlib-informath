#!/bin/sh
# Write the tactic proofs of a Lean file as Verbose Lean proofs and check them
# with Verbose (see README.md, "Verbose as an output style"):
#
#     ./verbalize.sh SeqContVerbose-input.lean     # -> SeqContVerbose.lean, checked
#
# The input has theorems marked #verbalize "title" (see VerboseGen.lean), with
# the definitions of Verbose's ExampleLib in scope.  VERBOSE is the Verbose
# Lean checkout, built (default ~/claude/verbose-lean4).
set -e
VERBOSE=${VERBOSE:-$HOME/claude/verbose-lean4}
HERE=$(cd "$(dirname "$0")" && pwd)
IN=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
OUT=$(dirname "$IN")/$(basename "$IN" -input.lean).lean
TMP=$(mktemp -d)
cat "$HERE/VerboseGen.lean" "$IN" > "$TMP/Gen.lean"
(cd "$VERBOSE" && lake env lean "$TMP/Gen.lean") > "$TMP/gen.out" 2>&1 || true
{
  echo "import Verbose.English.ExampleLib"
  echo "-- generated by verbalize.sh from $(basename "$IN"): Verbose Lean proofs of its"
  echo "-- tactic proofs, checked by Lean with Verbose"
  echo
  # the Example ... QED blocks that #verbalize prints
  awk '/^open Verbose.Named in$/{on=1} /^Example /{on=1} on{print} /^QED$/{on=0; print ""}' "$TMP/gen.out"
} > "$OUT"
echo "$OUT: $(grep -c '^Example ' "$OUT") proofs"
grep -E "error" "$TMP/gen.out" || true
echo "checking with Verbose:"
(cd "$VERBOSE" && lake env lean "$OUT") && echo "OK: all proofs check"
rm -rf "$TMP"
