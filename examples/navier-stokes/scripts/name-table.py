r"""navier-stokes-names.dkgf: every constant of NavierStokesAndEuler that the
exported modules declare or use, read by its last name component as an
operator, $\operatorname{Rapid}(#1)$, with its shown (not #HIDE) arguments.
The hand-written navier-stokes.dkgf, read after it, overrides it."""
import glob, os, re
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'exporter', 'out')
hidden = {}
for f in glob.glob(OUT + '/*-hide.dkgf'):
    for l in open(f):
        w = l.split()
        if len(w) > 2 and w[0] == '#HIDE':
            hidden[w[1]] = set(map(int, w[2:]))
def binders(t):
    """The number of named binders (x : A) -> at the top of a Dedukti type."""
    n, i = 0, 0
    while True:
        m = re.match(r'\s*\(\s*[A-Za-z0-9_\']+\s*:', t[i:])
        if not m:
            return n
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return n
        n, i = n + 1, j + m2.end()
types = {}
for f in glob.glob(OUT + '/*.dk'):
    for l in open(f):
        m = re.match(r'(?:def )?((?:NavierStokes|Euler|Comparator)[A-Za-z0-9]*__[A-Za-z0-9_\']+) : (.*?)(?:\.|\s*:=)\s*$', l)
        if m:
            types.setdefault(m.group(1), m.group(2))
out = ['# generated by scripts/name-table.py; overridden by navier-stokes.dkgf']
def codomain(t):
    # the type after the top binders
    n, i = 0, 0
    while True:
        m = re.match(r'\s*\(\s*[A-Za-z0-9_\']+\s*:', t[i:])
        if not m:
            return t[i:].strip()
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return t[i:].strip()
        i = j + m2.end()
NOARGS = os.environ.get('NOARGS')
for c, t in sorted(types.items()):
    if re.search(r'__(part|app)\d+$', c):
        continue                        # Export.lean writes their entries (-hide.dkgf)
    if codomain(t).startswith('Proof'):
        continue                        # a theorem: not a symbol
    n = 0 if NOARGS else binders(t)
    shown = [k for k in range(1, n + 1) if k not in hidden.get(c, set())]
    name = c.split('__')[-1].replace('_', r'\_').replace("'", r"'")
    op = r'\operatorname{%s}' % name
    if shown:
        out.append('%s : $%s(%s)$' % (c, op, ', '.join('#%d' % (i + 1) for i in range(len(shown)))))
    else:
        out.append('%s : $%s$' % (c, op))
# the hand-written entries must have one #k per shown argument
arity = {}
for l in out[1:]:
    c, e = l.split(' : ', 1)
    arity[c] = len(set(re.findall(r'#(\d+)', e)))
hand = os.path.join(OUT, '..', '..', 'navier-stokes.dkgf')
for l in open(hand):
    m = re.match(r'(\S+) : (.*)', l)
    if m and m.group(1) in arity:
        k = len(set(re.findall(r'#(\d+)', m.group(2))))
        if k != arity[m.group(1)]:
            print('navier-stokes.dkgf: %s has %d arguments, its applications %d' % (m.group(1), k, arity[m.group(1)]))
open(os.path.join(OUT, '..', '..', 'navier-stokes-names.dkgf'), 'w').write('\n'.join(out) + '\n')
print(len(types), 'constants -> navier-stokes-names.dkgf')
