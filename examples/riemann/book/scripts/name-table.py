B = re.compile(r"\s*\(\s*([A-Za-z0-9_']+|\{\|[^|]*\|\})\s*:")
def typed_binders(t):
    out, i = [], 0
    while True:
        m = B.match(t[i:])
        if not m:
            return out
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        out.append(t[i:j][t[i:j].index(':') + 1:-1].strip())
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return out
        i = j + m2.end()
