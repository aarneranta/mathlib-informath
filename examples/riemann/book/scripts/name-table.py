import unicodedata
ALPHABETS = [('MATHEMATICAL FRAKTUR', r'\mathfrak'), ('MATHEMATICAL DOUBLE-STRUCK', r'\mathbb'),
             ('MATHEMATICAL SCRIPT', r'\mathcal'), ('MATHEMATICAL BOLD', r'\mathbf'),
             ('MATHEMATICAL SANS-SERIF', r'\mathsf'), ('MATHEMATICAL ITALIC', r'\mathit')]
GREEK_VARIANTS = {'GREEK RHO SYMBOL': r'\varrho', 'GREEK PHI SYMBOL': r'\varphi', 'GREEK THETA SYMBOL': r'\vartheta',
                  'GREEK SMALL LETTER FINAL SIGMA': r'\varsigma', 'GREEK SMALL LETTER EPSILON': r'\varepsilon'}


def symbol(ch):
    """A character of a Lean name in LaTeX: Greek letters, the letters of the
    mathematical alphabets (𝔷 is \\mathfrak{z}), subscript digits."""
    n = unicodedata.name(ch, '')
    if n in GREEK_VARIANTS:
        return GREEK_VARIANTS[n]
    m = re.match(r'GREEK (SMALL|CAPITAL) LETTER (\w+)$', n)
    if m:
        w = m.group(2).lower()
        if m.group(1) == 'CAPITAL':
            w = w.capitalize()
            if w in ('Alpha', 'Beta', 'Epsilon', 'Zeta', 'Eta', 'Iota', 'Kappa', 'Mu', 'Nu', 'Omicron', 'Rho', 'Tau', 'Chi'):
                return r'\mathrm{%s}' % ch
        return '\\' + w
    for pre, cmd in ALPHABETS:
        m = re.match(pre + r' (SMALL|CAPITAL) (\w)$', n)
        if m:
            return '%s{%s}' % (cmd, m.group(2) if m.group(1) == 'CAPITAL' else m.group(2).lower())
    m = re.match(r'SUBSCRIPT (ZERO|ONE|TWO|THREE|FOUR|FIVE|SIX|SEVEN|EIGHT|NINE)$', n)
    if m:
        return '_{%d}' % ['ZERO', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE'].index(m.group(1))
    return None


def display(name):
    """A component of a Dedukti name (with Export.lean's _u<hex>_ for the
    characters that are not ASCII) as a LaTeX operator: rapid as
    \\operatorname{rapid}, _u1d537_ (𝔷) as \\mathfrak{z}, Data.ϱ as \\varrho."""
    parts = re.split(r'(_u[0-9a-f]+_)', name)
    out, text = [], ''
    for p in parts:
        m = re.fullmatch(r'_u([0-9a-f]+)_', p)
        s = symbol(chr(int(m.group(1), 16))) if m else None
        if s:
            if text:
                out.append(text if re.fullmatch(r'[A-Za-z]', text) else r'\operatorname{%s}' % text.replace('_', r'\_'))
                text = ''
            out.append(s)
        elif m:
            text += chr(int(m.group(1), 16))
        else:
            text += p
    if text:
        # a single letter (D.a, D.x, P.d) is a variable of the text: in italics
        out.append(text if re.fullmatch(r'[A-Za-z]', text) else r'\operatorname{%s}' % text.replace('_', r'\_'))
    return ''.join(out) or r'\operatorname{%s}' % name
# the number of arguments each constant is applied to in the statements: a
# constant whose value is a function (Matrix.mulVec M v, a function of i) is
# mostly applied to fewer arguments than its type has, and an entry fits
# only the applications with as many arguments as it has
import collections
TOK = re.compile(r"\{\|[^|]*\|\}|[A-Za-z_][\w'!?]*|->|=>|[():,.]|\S")
applied = collections.defaultdict(collections.Counter)
for f in glob.glob(OUT + '/*.dk'):
    if f.endswith('-deps.dk'):
        continue
    toks = TOK.findall(open(f).read())
    for i, w in enumerate(toks):
        if w not in types:
            continue
        if i == 0 or toks[i - 1] not in ('(', ':', '=>', '->', ',', ':='):
            applied[w][0] += 1          # an argument itself, not applied
            continue
        k, j = 0, i + 1
        while j < len(toks) and toks[j] not in (')', '->', '=>', ':', ',', '.', ':='):
            if toks[j] == '(':
                d = 0
                while j < len(toks):
                    d += {'(': 1, ')': -1}.get(toks[j], 0)
                    j += 1
                    if d == 0:
                        break
            else:
                j += 1
            k += 1
        applied[w][k] += 1


def shown_arity(c, n):
    """The shown arguments of the applications of c, the most frequent
    number; n (those of its type) if it is not applied."""
    if not applied[c]:
        return n
    k = applied[c].most_common(1)[0][0]
    return len([i for i in range(1, k + 1) if i not in hidden.get(c, set())])


