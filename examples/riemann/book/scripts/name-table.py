r"""grh-names.dkgf: every constant of riemann-hypothesis-original that the
exported modules declare or use, read by its last name component as an
operator, $\operatorname{Rapid}(#1)$, with its shown (not #HIDE) arguments.
The hand-written riemann.dkgf, read after it, overrides it."""
import glob, importlib.util, os, re
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'exporter', 'out')
hidden = {}
for f in glob.glob(OUT + '/*-hide.dkgf'):
    for l in open(f):
        w = l.split()
        if len(w) > 2 and w[0] == '#HIDE':
            hidden[w[1]] = set(map(int, w[2:]))
def binders(t):
    """The number of named binders (x : A) -> at the top of a Dedukti type."""
    n, i = 0, 0
    while True:
        m = re.match(r'\s*\(\s*(?:[A-Za-z0-9_\']+|\{\|[^|]*\|\})\s*:', t[i:])
        if not m:
            return n
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return n
        n, i = n + 1, j + m2.end()
spec = importlib.util.spec_from_file_location('ct', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'constants-table.py'))
ct = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ct)
leans = ct.lean_names()
orig = ct.origins(set(leans.values()))
project = {dk for dk, lean in leans.items() if ct.in_project(orig.get(lean, ('', ''))[0])}
types = {}
for f in glob.glob(OUT + '/*.dk'):
    for l in open(f):
        m = re.match(r'(?:def )?([A-Za-z_][A-Za-z0-9_\']*) : (.*?)(?:\.|\s*:=)\s*$', l)
        if m and m.group(1) in project:
            types.setdefault(m.group(1), m.group(2))
out = ['# generated by scripts/name-table.py; overridden by riemann.dkgf']
def codomain(t):
    # the type after the top binders
    n, i = 0, 0
    while True:
        m = re.match(r'\s*\(\s*(?:[A-Za-z0-9_\']+|\{\|[^|]*\|\})\s*:', t[i:])
        if not m:
            return t[i:].strip()
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return t[i:].strip()
        i = j + m2.end()
NOARGS = os.environ.get('NOARGS')
FIXED = {'Data', 'Parameters'}
import unicodedata
ALPHABETS = [('MATHEMATICAL FRAKTUR', r'\mathfrak'), ('MATHEMATICAL DOUBLE-STRUCK', r'\mathbb'),
             ('MATHEMATICAL SCRIPT', r'\mathcal'), ('MATHEMATICAL BOLD', r'\mathbf'),
             ('MATHEMATICAL SANS-SERIF', r'\mathsf'), ('MATHEMATICAL ITALIC', r'\mathit')]
GREEK_VARIANTS = {'GREEK RHO SYMBOL': r'\varrho', 'GREEK PHI SYMBOL': r'\varphi', 'GREEK THETA SYMBOL': r'\vartheta',
                  'GREEK SMALL LETTER FINAL SIGMA': r'\varsigma', 'GREEK SMALL LETTER EPSILON': r'\varepsilon'}


def symbol(ch):
    """A character of a Lean name in LaTeX: Greek letters, the letters of the
    mathematical alphabets (𝔷 is \\mathfrak{z}), subscript digits."""
    n = unicodedata.name(ch, '')
    if n in GREEK_VARIANTS:
        return GREEK_VARIANTS[n]
    m = re.match(r'GREEK (SMALL|CAPITAL) LETTER (\w+)$', n)
    if m:
        w = m.group(2).lower()
        if m.group(1) == 'CAPITAL':
            w = w.capitalize()
            if w in ('Alpha', 'Beta', 'Epsilon', 'Zeta', 'Eta', 'Iota', 'Kappa', 'Mu', 'Nu', 'Omicron', 'Rho', 'Tau', 'Chi'):
                return r'\mathrm{%s}' % ch
        return '\\' + w
    for pre, cmd in ALPHABETS:
        m = re.match(pre + r' (SMALL|CAPITAL) (\w)$', n)
        if m:
            return '%s{%s}' % (cmd, m.group(2) if m.group(1) == 'CAPITAL' else m.group(2).lower())
    m = re.match(r'SUBSCRIPT (ZERO|ONE|TWO|THREE|FOUR|FIVE|SIX|SEVEN|EIGHT|NINE)$', n)
    if m:
        return '_{%d}' % ['ZERO', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE'].index(m.group(1))
    return None


def display(name):
    """A component of a Dedukti name (with Export.lean's _u<hex>_ for the
    characters that are not ASCII) as a LaTeX operator: rapid as
    \\operatorname{rapid}, _u1d537_ (𝔷) as \\mathfrak{z}, Data.ϱ as \\varrho."""
    parts = re.split(r'(_u[0-9a-f]+_)', name)
    out, text = [], ''
    for p in parts:
        m = re.fullmatch(r'_u([0-9a-f]+)_', p)
        s = symbol(chr(int(m.group(1), 16))) if m else None
        if s:
            if text:
                out.append(text if re.fullmatch(r'[A-Za-z]', text) else r'\operatorname{%s}' % text.replace('_', r'\_'))
                text = ''
            out.append(s)
        elif m:
            text += chr(int(m.group(1), 16))
        else:
            text += p
    if text:
        # a single letter (D.a, D.x, P.d) is a variable of the text: in italics
        out.append(text if re.fullmatch(r'[A-Za-z]', text) else r'\operatorname{%s}' % text.replace('_', r'\_'))
    return ''.join(out) or r'\operatorname{%s}' % name
for c, t in sorted(types.items()):
    if re.search(r'__(part|app)\d+$', c):
        continue                        # Export.lean writes their entries (-hide.dkgf)
    if codomain(t).startswith('Proof'):
        continue                        # a theorem: not a symbol
    n = 0 if NOARGS else binders(t)
    shown = [k for k in range(1, n + 1) if k not in hidden.get(c, set())]
    op = display(c.split('__')[-1])
    ks = ['#%d' % (i + 1) for i in range(len(shown))]
    # the fields of the data D and the parameters P, which are fixed throughout
    # (grh's GUIDE: "Throughout, P : Parameters and D : Data P"), without D and P
    if c.split('__')[0] in FIXED and ks:
        ks = ks[1:]
    if ks:
        out.append('%s : $%s(%s)$' % (c, op, ', '.join(ks)))
    else:
        out.append('%s : $%s$' % (c, op))
# the hand-written entries must have one #k per shown argument
arity = {}
for l in out[1:]:
    c, e = l.split(' : ', 1)
    arity[c] = len(set(re.findall(r'#(\d+)', e)))
hand = os.path.join(OUT, '..', '..', 'grh.dkgf')
