def binders(t):
    """The number of named binders (x : A) -> at the top of a Dedukti type."""
    n, i = 0, 0
    while True:
        m = re.match(r'\s*\(\s*(?:[A-Za-z0-9_\']+|\{\|[^|]*\|\})\s*:', t[i:])
        if not m:
            return n
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return n
        n, i = n + 1, j + m2.end()
