r"""riemann-names.dkgf: every constant of riemann-hypothesis-original that the
exported modules declare or use, read by its last name component as an
operator, $\operatorname{Rapid}(#1)$, with its shown (not #HIDE) arguments.
The hand-written riemann.dkgf, read after it, overrides it."""
import glob, importlib.util, os, re
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'exporter', 'out')
hidden = {}
for f in glob.glob(OUT + '/*-hide.dkgf'):
    for l in open(f):
        w = l.split()
        if len(w) > 2 and w[0] == '#HIDE':
            hidden[w[1]] = set(map(int, w[2:]))
def binders(t):
    """The number of named binders (x : A) -> at the top of a Dedukti type."""
    n, i = 0, 0
    while True:
        m = re.match(r'\s*\(\s*(?:[A-Za-z0-9_\']+|\{\|[^|]*\|\})\s*:', t[i:])
        if not m:
            return n
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return n
        n, i = n + 1, j + m2.end()
spec = importlib.util.spec_from_file_location('ct', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'constants-table.py'))
ct = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ct)
leans = ct.lean_names()
orig = ct.origins(set(leans.values()))
project = {dk for dk, lean in leans.items() if ct.in_project(orig.get(lean, ('', ''))[0])}
types = {}
for f in glob.glob(OUT + '/*.dk'):
    for l in open(f):
        m = re.match(r'(?:def )?([A-Za-z_][A-Za-z0-9_\']*) : (.*?)(?:\.|\s*:=)\s*$', l)
        if m and m.group(1) in project:
            types.setdefault(m.group(1), m.group(2))
out = ['# generated by scripts/name-table.py; overridden by riemann.dkgf']
def codomain(t):
    # the type after the top binders
    n, i = 0, 0
    while True:
        m = re.match(r'\s*\(\s*(?:[A-Za-z0-9_\']+|\{\|[^|]*\|\})\s*:', t[i:])
        if not m:
            return t[i:].strip()
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return t[i:].strip()
        i = j + m2.end()
NOARGS = os.environ.get('NOARGS')
for c, t in sorted(types.items()):
    if re.search(r'__(part|app)\d+$', c):
        continue                        # Export.lean writes their entries (-hide.dkgf)
    if codomain(t).startswith('Proof'):
        continue                        # a theorem: not a symbol
    n = 0 if NOARGS else binders(t)
    shown = [k for k in range(1, n + 1) if k not in hidden.get(c, set())]
    name = c.split('__')[-1].replace('_', r'\_').replace("'", r"'")
    op = r'\operatorname{%s}' % name
    if shown:
        out.append('%s : $%s(%s)$' % (c, op, ', '.join('#%d' % (i + 1) for i in range(len(shown)))))
    else:
        out.append('%s : $%s$' % (c, op))
# the hand-written entries must have one #k per shown argument
arity = {}
for l in out[1:]:
    c, e = l.split(' : ', 1)
    arity[c] = len(set(re.findall(r'#(\d+)', e)))
hand = os.path.join(OUT, '..', '..', 'riemann.dkgf')
for l in (open(hand) if os.path.exists(hand) else []):
    m = re.match(r'(\S+) : (.*)', l)
    if m and m.group(1) in arity:
        k = len(set(re.findall(r'#(\d+)', m.group(2))))
        if k != arity[m.group(1)]:
            print('riemann.dkgf: %s has %d arguments, its applications %d' % (m.group(1), k, arity[m.group(1)]))
# c__in<k>: c with an instance that the statement gives (Export.lean), here
# the valuation of a completion (GlobalTheory.LocalData.complRel, a local
# instance), shown as an argument of its own: its entry is c's entry, with c's
# arguments where they are among c__in's and the instance left out
MI = os.path.join(OUT, '..', '..', '..', '..')
entry = {}
for t in [os.path.join(MI, f) for f in ['definitions.dkgf', 'mathlib.dkgf', 'structures.dkgf']] + [None, hand]:
    for l in (out[1:] if t is None else open(t) if os.path.exists(t) else []):
        m = re.match(r"([A-Za-z_][\w']*) : (.*)", l.rstrip('\n'))
        if m and not l.startswith('#'):
            entry[m.group(1)] = m.group(2)
B = re.compile(r"\s*\(\s*([A-Za-z0-9_']+|\{\|[^|]*\|\})\s*:")
def typed_binders(t):
    out, i = [], 0
    while True:
        m = B.match(t[i:])
        if not m:
            return out
        d, j = 0, i + t[i:].index('(')
        while True:
            d += {'(': 1, ')': -1}.get(t[j], 0)
            j += 1
            if d == 0:
                break
        out.append(t[i:j][t[i:j].index(':') + 1:-1].strip())
        m2 = re.match(r'\s*->', t[j:])
        if not m2:
            return out
        i = j + m2.end()
alltypes = {}
for f in glob.glob(OUT + '/*.dk'):
    for l in open(f):
        m = re.match(r"(?:def )?([A-Za-z_][\w']*__in(?:_\d+)*) : (.*?)(?:\.|\s*:=)\s*$", l)
        if m:
            alltypes.setdefault(m.group(1), m.group(2))
derived = 0
for c, t in sorted(alltypes.items()):
    base = re.sub(r'__in(_\d+)*$', '', c)
    if base not in entry or c in entry:
        continue
    bs = typed_binders(t)
    shown = [k for k in range(1, len(bs) + 1) if k not in hidden.get(c, set())]
    rest = [i for i, k in enumerate(shown, 1) if not re.match(r'Elem \(\S+__on\b', bs[k - 1])]
    e = entry[base]
    ks = [int(k) for k in re.findall(r'#(\d+)', e)]
    if not ks or max(ks) > len(rest):
        continue
    out.append('%s : %s' % (c, re.sub(r'#(\d+)', lambda m: '#%d' % rest[int(m.group(1)) - 1], e)))
    derived += 1
print(derived, 'c__in entries derived from the entries of c')
open(os.path.join(OUT, '..', '..', 'riemann-names.dkgf'), 'w').write('\n'.join(out) + '\n')
print(len(types), 'constants -> riemann-names.dkgf')
